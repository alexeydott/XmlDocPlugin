param(
 [string]$Rad12='D:\Embarcadero RAD Studio\23.0',
 [string]$Rad13='D:\Embarcadero RAD Studio\37.0'
)
$ErrorActionPreference='Stop'
$work=Join-Path $env:LOCALAPPDATA 'XmlDocPlugin\SystemDeclarations'
New-Item -ItemType Directory -Force $work | Out-Null
$keywords='and,array,as,asm,begin,case,class,const,constructor,destructor,dispinterface,div,do,downto,else,end,except,exports,file,finalization,finally,for,function,goto,if,implementation,in,inherited,initialization,inline,interface,is,label,library,mod,nil,not,object,of,on,or,out,packed,procedure,program,property,raise,record,repeat,resourcestring,set,shl,shr,string,then,threadvar,to,try,type,unit,until,uses,var,while,with,xor'.Split(',')
$tables=@{}
foreach($target in @(@{Name='Rad12Win32';Root=$Rad12;Compiler='dcc32'},@{Name='Rad12Win64';Root=$Rad12;Compiler='dcc64'},@{Name='Rad13Win32';Root=$Rad13;Compiler='dcc32'},@{Name='Rad13Win64';Root=$Rad13;Compiler='dcc64'})) {
 $system=Join-Path $target.Root 'source\rtl\sys\System.pas'
 $names=[regex]::Matches([IO.File]::ReadAllText($system),'\b[A-Za-z_][A-Za-z_0-9]*\b').Value | Sort-Object -Unique | Where-Object {$_ -notin $keywords}

 $lines=[Collections.Generic.List[string]]::new()
 $lines.Add('program XmlDocSystemScopeInventory9827; {$APPTYPE CONSOLE}')
 $bases=@([regex]::Matches([IO.File]::ReadAllText($system),'(?m)^\s*(\w+)\s*=\s*class(?:\s*\(|\s*$)') | ForEach-Object {$_.Groups[1].Value} | Sort-Object -Unique)
 foreach($base in $bases){$lines.Add(('{{$IF DECLARED({0})}} type TXmlDocScopeInventory9827{0}=class({0}) class procedure Emit9827; end; {{$IFEND}}' -f $base))}
 $lines.Add('procedure EmitGlobals9827; begin')
 foreach($name in $names){$lines.Add(('{{$IF DECLARED({0})}} Writeln(''G:{0}''); {{$IFEND}}' -f $name))}
 $lines.Add('end;')
 foreach($base in $bases) {
  $lines.Add(('{{$IF DECLARED({0})}} class procedure TXmlDocScopeInventory9827{0}.Emit9827; begin' -f $base))
  foreach($name in $names){$lines.Add(('{{$IF DECLARED({0})}} Writeln(''M:{1}:{0}''); {{$IFEND}}' -f $name,$base))}
  $lines.Add('end; {$IFEND}')
 }
 $lines.Add('begin EmitGlobals9827;')
 foreach($base in $bases){$lines.Add(('{{$IF DECLARED({0})}} TXmlDocScopeInventory9827{0}.Emit9827; {{$IFEND}}' -f $base))}
 $lines.Add('end.')
 $dir=Join-Path $work $target.Name;New-Item -ItemType Directory -Force $dir | Out-Null
 $source=Join-Path $dir 'Inventory.dpr'
 [IO.File]::WriteAllLines($source,$lines,[Text.UTF8Encoding]::new($false))
 & cmd.exe /d /c "`"$($target.Root)\bin\rsvars.bat`" && $($target.Compiler) -B --codepage:65001 `"-E$dir`" `"-N0$dir`" `"$source`"" *> "$dir\build.log"
 if($LASTEXITCODE){Get-Content "$dir\build.log" -Tail 12;throw "Inventory compilation failed: $($target.Name)"}
 $output=& "$dir\Inventory.exe"
 if($LASTEXITCODE){throw 'Inventory execution failed'}
 $globals=@($output | Where-Object {$_ -like 'G:*'} | ForEach-Object {$_.Substring(2).ToUpperInvariant()} | Sort-Object -Unique)
 $members=@($output | Where-Object {$_ -like 'M:*'} | ForEach-Object {$_.Substring(2).ToUpperInvariant().Replace(':','.')} | Where-Object {($_.Split('.')[-1]) -notin $globals -and ($_.Split('.')[-1]) -notin @('SELF','RESULT')} | Sort-Object -Unique)
 $classes=@($bases | Where-Object {$_.ToUpperInvariant() -in $globals} | ForEach-Object {$_.ToUpperInvariant()})
 $tables[$target.Name]=@{Globals=$globals;Members=$members;Classes=$classes}
 "PASS $($target.Name): $($globals.Count) globals, $($members.Count) System class members"
}
$lines=[Collections.Generic.List[string]]::new()
$lines.Add('// Generated by tools/Generate-SystemDeclarations.ps1 using native Delphi compilers.')
$lines.Add('const')
foreach($name in @('Rad12Win32','Rad12Win64','Rad13Win32','Rad13Win64')) {
 foreach($kind in @('Globals','Members','Classes')) {
  $value='|'+($tables[$name][$kind] -join '|')+'|'
  $lines.Add("  C${name}${kind} =")
  for($offset=0;$offset -lt $value.Length;$offset+=100){$chunk=$value.Substring($offset,[Math]::Min(100,$value.Length-$offset));$suffix=if($offset+100 -ge $value.Length){';'}else{' +'};$lines.Add("    '$chunk'$suffix")}
 }
}
[IO.File]::WriteAllLines((Join-Path $PSScriptRoot '..\src\Core\XmlDoc.SystemDeclarations.inc'),$lines,[Text.UTF8Encoding]::new($false))
