param([switch]$Check)
$ErrorActionPreference='Stop'
$xsl=[IO.File]::ReadAllText((Join-Path $PSScriptRoot 'resources/helpinsight/HelpInsight.xsl')).Replace("`r`n","`n")
$generated="{ Generated by build-helpinsight.ps1. }`nconst CEnhancedHelpInsightXslt =`n"
$lines=$xsl.TrimEnd().Split("`n")
for($i=0;$i -lt $lines.Count;$i++){
 $chunks=@();for($offset=0;$offset -lt $lines[$i].Length;$offset+=180){$chunks+="'"+$lines[$i].Substring($offset,[Math]::Min(180,$lines[$i].Length-$offset)).Replace("'","''")+"'"}
 if(!$chunks.Count){$chunks=@("''")}
 $generated+='  '+($chunks -join " +`n  ")+$(if($i -eq $lines.Count-1){";`n"}else{" + #10 +`n"})
}
$path=Join-Path $PSScriptRoot 'src/Plugin/XmlDoc.HelpInsight.Template.inc'
if($Check){if([IO.File]::ReadAllText($path).Replace("`r`n","`n") -ne $generated){throw 'Help Insight template is stale. Run build-helpinsight.ps1.'}}else{[IO.File]::WriteAllText($path,$generated,[Text.UTF8Encoding]::new($true))}
